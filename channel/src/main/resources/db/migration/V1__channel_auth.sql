CREATE TABLE auth_user (
  id BIGSERIAL PRIMARY KEY, username VARCHAR(120) NOT NULL UNIQUE,
  password_hash VARCHAR(100) NOT NULL, display_name VARCHAR(120) NOT NULL,
  email VARCHAR(200) NOT NULL UNIQUE, enabled BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE password_reset (
  id BIGSERIAL PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES auth_user(id),
  token_hash VARCHAR(64) NOT NULL UNIQUE, expires_at TIMESTAMPTZ NOT NULL,
  used_at TIMESTAMPTZ, created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
